import { computed, ref } from 'vue'
import { appStore, getDefaultExpression, getExtraDefaultExpressions, namesOf } from './app-state'
import { defaultFaceConfig, defaultFeatureConfig } from './config-defaults'
import {
  BOOP_EXPRESSION_DEFAULTS,
  DEFAULT_FACE_NAME,
  EXTRA_DEFAULT_NAMES,
  REMOTE_ACTION_DEFAULTS,
  SLOW_MOVEMENT_NAMES,
  VERY_SLOW_MOVEMENT_NAMES,
} from '@/faces/faces'
import { usableBoopExpressions } from './boop-expressions'
import { defaultExpressions } from './expressions'
import { downloadBlob, generateConfigHeader } from './generate-config'
import {
  generateFacesHeader,
  type BoopExpressionEntry,
  type RemoteActionEntry,
} from './generate-faces'
import { usableRemoteActions } from './remote-actions'

export type DownloadKind = 'config' | 'expressions'

export const DOWNLOADS: Record<DownloadKind, { fileName: string; label: string }> = {
  config: { fileName: 'Config.h', label: 'config' },
  expressions: { fileName: 'Protogen_Faces.h', label: 'expressions' },
}

const KINDS = Object.keys(DOWNLOADS) as DownloadKind[]

/** Written into downloaded files. Bump it when the generated format changes */
const FORMAT_VERSION = 7

function generateFiles(
  face: typeof appStore.faceConfig,
  features: typeof appStore.featureConfig,
  expressions: typeof appStore.expressions,
  defaultExpressionName: string,
  extraDefaultNames: string[],
  boopExpressions: BoopExpressionEntry[],
  remoteActions: RemoteActionEntry[],
  movement: { slow: string[]; verySlow: string[] },
): Record<DownloadKind, string> {
  return {
    config: generateConfigHeader(face, features),
    expressions: generateFacesHeader(
      expressions,
      defaultExpressionName,
      extraDefaultNames,
      boopExpressions,
      remoteActions,
      movement,
    ),
  }
}

/** Each file as of its last download. Starts as the ToasterOS defaults. */
const lastDownloaded = ref(
  generateFiles(
    defaultFaceConfig(),
    defaultFeatureConfig(),
    defaultExpressions(),
    DEFAULT_FACE_NAME,
    EXTRA_DEFAULT_NAMES.filter((name) => name !== DEFAULT_FACE_NAME),
    BOOP_EXPRESSION_DEFAULTS,
    REMOTE_ACTION_DEFAULTS,
    { slow: SLOW_MOVEMENT_NAMES, verySlow: VERY_SLOW_MOVEMENT_NAMES },
  ),
)

const currentFiles = computed(() =>
  generateFiles(
    appStore.faceConfig,
    appStore.featureConfig,
    appStore.expressions,
    getDefaultExpression().name,
    getExtraDefaultExpressions().map((e) => e.name),
    usableBoopExpressions(appStore.boopExpressions, appStore.expressions).map((b) => ({
      minBoops: b.minBoops,
      name: b.expression.name,
    })),
    usableRemoteActions(appStore.remoteActions, appStore.expressions),
    {
      slow: namesOf(appStore.slowMovementExpressionIds),
      verySlow: namesOf(appStore.verySlowMovementExpressionIds),
    },
  ),
)

/** Files that have changed since they were last downloaded */
export const changedDownloads = computed(() =>
  KINDS.filter((kind) => currentFiles.value[kind] !== lastDownloaded.value[kind]),
)

export const hasUndownloadedChanges = computed(() => changedDownloads.value.length > 0)

export function hasChanged(kind: DownloadKind) {
  return changedDownloads.value.includes(kind)
}

/** e.g. "2026-11-21 14:03:12 (UTC+00:00)", in the user's local time */
function formatTimestamp(date: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0')
  const offset = -date.getTimezoneOffset()
  const sign = offset >= 0 ? '+' : '-'
  const offsetText = `${pad(Math.floor(Math.abs(offset) / 60))}:${pad(Math.abs(offset) % 60)}`
  return (
    `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ` +
    `${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())} ` +
    `(UTC${sign}${offsetText})`
  )
}

export function downloadFile(kind: DownloadKind) {
  const contents = currentFiles.value[kind]
  // The timestamp is only added to the downloaded file, so it doesn't count as a change
  const stamped =
    `// Generated by Toaster Oven on ${formatTimestamp(new Date())}\n` +
    `// Toaster Oven format: ${FORMAT_VERSION}\n\n${contents}`
  downloadBlob(DOWNLOADS[kind].fileName, new Blob([stamped], { type: 'text/plain' }))
  lastDownloaded.value = { ...lastDownloaded.value, [kind]: contents }
}

/** Treat the current state as already downloaded, e.g. after importing that same file */
export function markDownloaded(kind: DownloadKind) {
  lastDownloaded.value = { ...lastDownloaded.value, [kind]: currentFiles.value[kind] }
}
