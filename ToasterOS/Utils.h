int PrintF(const char* format, ...) {
  static char buffer[1024];  // Adjust to your needs
  va_list aptr;
  va_start(aptr, format);
  int results = vsnprintf(buffer, sizeof(buffer), format, aptr);
  va_end(aptr);
  Serial.print(buffer);
  return results;
}


